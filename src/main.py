"""
КонспектХаб (NoteSwap)
Простое приложение для обмена конспектами между студентами.
"""

def create_request_stub():
    """Заглушка для функции создания нового запроса (Задача 3 из Backlog)."""
    print("\n--- Создание нового запроса ---")
    print("Здесь будет форма ввода: Предмет, Тема, Дата, Тип (Ищу/Предлагаю)")
    print("Функция находится в разработке.\n")

def main():
    """Главная функция приложения."""
    while True:
        print("=" * 50)
        print("КонспектХаб — биржа конспектов и материалов")
        print("=" * 50)
        print("\nМеню:")
        print("1. Создать запрос на конспект")
        print("2. Просмотреть ленту запросов")
        print("3. Оставить контакт под запросом")
        print("0. Выход")
        
        choice = input("\nВыберите действие (0-3): ")
        
        if choice == '1':
            create_request_stub()
        elif choice == '2':
            print("\n[Заглушка] Лента запросов пока пуста.")
        elif choice == '3':
            print("\n[Заглушка] Функция оставления контакта в разработке.")
        elif choice == '0':
            print("\nДо свидания!\n")
            break
        else:
            print("\nНеверный ввод. Попробуйте снова.")

if __name__ == "__main__":
    main()
